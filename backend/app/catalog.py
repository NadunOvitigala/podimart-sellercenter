def category_by_id(category_id: str) -> dict | None:
    return next((item for item in CATEGORIES if item["id"] == category_id), None)


def subcategory_ids(category_id: str) -> set[str]:
    category = category_by_id(category_id)
    if not category:
        return set()
    return {item["id"] for item in category.get("subcategories") or []}
