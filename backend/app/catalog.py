def _subs(*names: str) -> list[dict[str, str]]:
    items: list[dict[str, str]] = []
    for name in names:
        slug = "".join(ch.lower() if ch.isalnum() else "-" for ch in name).strip("-")
        while "--" in slug:
            slug = slug.replace("--", "-")
        items.append({"id": slug[:64], "name": name})
    return items


